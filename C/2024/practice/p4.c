// 整数 n が1つ 0<=n<=90
// fib(0)=1 fib(1)=1 fib(n)=fib(n-1)+fib(n-2)
// fib(n) を 10000 で割った余りを出力する

#include <stdio.h>

int main(void){
    int n;
    scanf("%d",&n);

    // フィボナッチ数列（この問題の定義）
    // fib(0)=1
    // fib(1)=1
    // fib(n)=fib(n-1)+fib(n-2)  (n>=2)
    //
    // 素直に再帰で fib(n) を計算すると同じ計算を何回も繰り返して遅い。
    // そこで「一度計算したfib(i)を配列に保存して使い回す」= 動的計画法(DP)で解く。

    // dp[i] に fib(i) を入れる
    // 制約 0<=n<=90 なので 45 要素あれば足りる
    long long dp[91];

    // まずは基底条件（ここがスタート）
    dp[0]=1; // fib(0)
    dp[1]=1; // fib(1)

    // i=2 から n まで順番に作る
    // dp[i] を作るには dp[i-1] と dp[i-2] が必要なので
    // 小さい順に計算すれば必ず既に値が入っている
    for(int i=2;i<=n;i++){
        // 定義通りに足すだけ
        dp[i]=(dp[i-1]+dp[i-2]) % 10000;
    }

    // dp[n] が fib(n) そのもの
    // n=0,1 のときも dp[0],dp[1] が入っているのでこのまま出せる
    printf("%lld\n",dp[n]);

    return 0;
}
